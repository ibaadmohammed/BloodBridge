BEGIN;

-- 1. Extend the existing donor directory.
ALTER TABLE public.donor_directory
    ADD COLUMN IF NOT EXISTS gender VARCHAR(20),
    ADD COLUMN IF NOT EXISTS age INTEGER,
    ADD COLUMN IF NOT EXISTS weight_kg NUMERIC(5,2),
    ADD COLUMN IF NOT EXISTS state VARCHAR(100),
    ADD COLUMN IF NOT EXISTS registered_on DATE;

-- 2. Preserve the blood group from existing JSON appointments.
ALTER TABLE public.appointments
    ADD COLUMN IF NOT EXISTS blood_group VARCHAR(3);

-- 3. Create a dedicated directory for blood banks.
CREATE TABLE IF NOT EXISTS public.blood_banks (
    blood_bank_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id TEXT NOT NULL UNIQUE,
    bank_name VARCHAR(200) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100),
    address TEXT,
    latitude NUMERIC(10,7),
    longitude NUMERIC(10,7),
    phone VARCHAR(20)
);

-- 4. Add an index for city-based blood-bank searches.
CREATE INDEX IF NOT EXISTS idx_blood_banks_city
    ON public.blood_banks(city);

COMMIT;
